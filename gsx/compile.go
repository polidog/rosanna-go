package gsx

import (
	"fmt"
	goparser "go/parser"
	"html"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// RuntimeImport は生成コードが読み込むランタイムのパッケージです。
const RuntimeImport = "github.com/polidog/rosanna-go"

// runtimeName は生成コードがランタイムを参照するときの名前。利用者の import と重ならないようにする
const runtimeName = "gsxrt"

// Header は生成したファイルの先頭行です。
const Header = "// Code generated by gsx. DO NOT EDIT."

var (
	leadingNewline  = regexp.MustCompile(`\A[ \t\r\f\v]*\n\s*`)
	trailingNewline = regexp.MustCompile(`\s*\n[ \t\r\f\v]*\z`)
	whitespaceRun   = regexp.MustCompile(`\s+`)
)

// 改行を含むテキストは前後の改行を含む空白を捨てる。残りの連続する空白は 1 つにまとめる
func normalizeText(text string) string {
	if strings.Contains(text, "\n") {
		text = leadingNewline.ReplaceAllString(text, "")
		text = trailingNewline.ReplaceAllString(text, "")
	}
	return whitespaceRun.ReplaceAllString(text, " ")
}

func decodeEntities(text string) string {
	return html.UnescapeString(text)
}

// Compile は .gsx のソースを Go のソースにします。filename は //line 指令とエラーに使います。
//
// 生成コードの行は .gsx の行と一致します。コンパイルエラーと panic の行は .gsx の行で報告されます。
func Compile(src []byte, filename string) ([]byte, error) {
	p := &parser{src: string(src), file: filename}
	code, _, err := p.parseGo(0, false)
	if err != nil {
		return nil, err
	}

	e := &emitter{p: p, line: 1}
	if err := e.goCode(code, false); err != nil {
		return nil, err
	}
	body := e.out.String()

	if e.usesRuntime {
		body, err = injectImport(p, body)
		if err != nil {
			return nil, err
		}
	}

	var out strings.Builder
	out.WriteString(Header + "\n")
	out.WriteString("//line " + filepath.Base(filename) + ":1\n")
	out.WriteString(body)
	return []byte(out.String()), nil
}

type emitter struct {
	p           *parser
	out         strings.Builder
	line        int // 出力の現在の行。ソースの行と揃える
	usesRuntime bool
}

func (e *emitter) write(s string) {
	e.out.WriteString(s)
	e.line += strings.Count(s, "\n")
}

// padTo は出力の行をソースの pos の行まで進める。改行で ; が入らない位置 ('(' や ',' の後) でだけ呼ぶ
func (e *emitter) padTo(pos int) {
	for target := e.p.line(pos); e.line < target; {
		e.write("\n")
	}
}

func (e *emitter) rt(name string) string {
	e.usesRuntime = true
	return runtimeName + "." + name
}

// goCode は Go のコードをそのまま書き、中のタグを変換する。inExpr なら {} の中の式で、末尾の空白を捨てる
func (e *emitter) goCode(code *goCode, inExpr bool) error {
	for i, part := range code.parts {
		switch v := part.(type) {
		case string:
			if i > 0 {
				if _, afterElement := code.parts[i-1].(*element); afterElement {
					v = pullCloser(v)
				}
			}
			if inExpr && i == len(code.parts)-1 {
				// 末尾の改行で ; が入らないようにする。行は次の padTo で揃う
				v = strings.TrimRight(v, " \t\r\n")
			}
			e.write(v)
		case *element:
			if err := e.element(v); err != nil {
				return err
			}
		}
	}
	return nil
}

var closerOnNextLine = regexp.MustCompile(`\A([ \t\r]*\n[ \t\r\n]*)((?:[)\]}][ \t]*)+)`)

// pullCloser は要素の後の「改行と閉じ括弧」を「閉じ括弧と改行」にする。
// return (<div>...</div>\n) の改行で ; が入らないようにする。行の数は変わらない
func pullCloser(s string) string {
	m := closerOnNextLine.FindStringSubmatchIndex(s)
	if m == nil {
		return s
	}
	return s[m[4]:m[5]] + s[m[2]:m[3]] + s[m[5]:]
}

func (e *emitter) expr(code *goCode, spread bool) error {
	if code.endsWithLineComment {
		return e.p.errorAt(code.start, "parse", "a // comment cannot end an expression in {}: use /* */")
	}
	if err := e.assertSingleExpression(code, spread); err != nil {
		return err
	}
	return e.goCode(code, true)
}

// {} の中は単独の式に限る。{a, b} は Go の引数の並びとして通ってしまうので、ここで止める
func (e *emitter) assertSingleExpression(code *goCode, spread bool) error {
	var b strings.Builder
	for _, part := range code.parts {
		switch v := part.(type) {
		case string:
			b.WriteString(v)
		case *element:
			b.WriteString("_gsx")
			// 行を数えるために、要素の中の改行を残す
			b.WriteString(strings.Repeat("\n", strings.Count(e.p.src[v.pos:v.closePos], "\n")))
		}
	}
	if _, err := goparser.ParseExpr(b.String()); err != nil {
		what := "{...}"
		if spread {
			what = "{...expr}"
		}
		return e.p.errorAt(code.start, "compile", "%s must hold a single Go expression: %v", what, err)
	}
	return nil
}

func (e *emitter) element(el *element) error {
	switch {
	case el.fragment:
		e.write(e.rt("Frag") + "(")
		if err := e.children(el.children); err != nil {
			return err
		}
	case isComponentName(el.name):
		if err := e.component(el); err != nil {
			return err
		}
	default:
		e.write(e.rt("El") + "(" + strconv.Quote(el.name) + ", ")
		if err := e.attributes(el); err != nil {
			return err
		}
		if err := e.children(el.children); err != nil {
			return err
		}
	}
	e.padTo(el.closePos)
	e.write(")")
	return nil
}

// 同名の属性は後の値が勝つ。位置は最初に書いたところ
func dedupe(attrs []*attribute, rename func(string) string) []*attribute {
	index := map[string]int{}
	var out []*attribute
	for _, a := range attrs {
		name := a.name
		if rename != nil {
			name = rename(name)
		}
		a = &attribute{pos: a.pos, name: name, kind: a.kind, str: a.str, expr: a.expr}
		if i, ok := index[name]; ok {
			a.pos = out[i].pos
			out[i] = a
			continue
		}
		index[name] = len(out)
		out = append(out, a)
	}
	return out
}

func (e *emitter) attrValue(a *attribute) error {
	switch a.kind {
	case attrString:
		e.write(strconv.Quote(a.str))
	case attrTrue:
		e.write("true")
	case attrExpr:
		return e.expr(a.expr, false)
	}
	return nil
}

func (e *emitter) attributes(el *element) error {
	attrs := dedupe(el.attrs, func(name string) string {
		if name == "for" {
			return "htmlFor"
		}
		return name
	})
	if len(attrs) == 0 {
		e.write("nil, ")
		return nil
	}
	e.write(e.rt("A") + "(")
	for _, a := range attrs {
		e.padTo(a.pos)
		e.write(strconv.Quote(a.name) + ", ")
		if err := e.attrValue(a); err != nil {
			return err
		}
		e.write(", ")
	}
	e.write("), ")
	return nil
}

func (e *emitter) children(children []*child) error {
	for _, c := range children {
		e.padTo(c.pos)
		if err := e.child(c); err != nil {
			return err
		}
		e.write(", ")
	}
	return nil
}

func (e *emitter) child(c *child) error {
	switch c.kind {
	case childText:
		e.write(strconv.Quote(c.text))
	case childExpr, childSpread:
		return e.expr(c.expr, c.kind == childSpread)
	case childElement:
		return e.element(c.el)
	}
	return nil
}

// component はコンポーネントを関数の呼び出しにする。<ui.Card title="t">x</ui.Card> は
// ui.Card(ui.CardProps{Title: "t", Children: "x"}) になる。フィールドの検査は Go のコンパイラに任せる
func (e *emitter) component(el *element) error {
	attrs, err := e.componentFields(el)
	if err != nil {
		return err
	}
	e.write(el.name + "(" + el.name + "Props{")
	for _, a := range attrs {
		if a.name == "Children" && len(el.children) > 0 {
			return e.p.errorAt(a.pos, "compile", "<%s> has both a children attribute and child nodes", el.name)
		}
		e.padTo(a.pos)
		e.write(a.name + ": ")
		if err := e.attrValue(a); err != nil {
			return err
		}
		e.write(", ")
	}

	// 子が 1 つなら配列にせずその値を渡す。{...xs} が 1 つならその値 (スライス) を渡す
	switch len(el.children) {
	case 0:
	case 1:
		e.padTo(el.children[0].pos)
		e.write("Children: ")
		if err := e.child(el.children[0]); err != nil {
			return err
		}
		e.write(", ")
	default:
		e.write("Children: []" + e.rt("Node") + "{")
		if err := e.children(el.children); err != nil {
			return err
		}
		e.write("}, ")
	}
	e.write("}, ")
	return nil
}

// componentFields は属性名を props のフィールド名にする。先頭だけを大文字にし、残りは書いたとおりに使う
// (title は Title、ID は ID)。同名は後の値が勝つ
func (e *emitter) componentFields(el *element) ([]*attribute, error) {
	renamed := make([]*attribute, 0, len(el.attrs))
	for _, a := range el.attrs {
		if !isGoFieldName(a.name) {
			return nil, e.p.errorAt(a.pos, "compile", "attribute %s of <%s> must be a Go identifier to name a field of %sProps", a.name, el.name, el.name)
		}
		renamed = append(renamed, &attribute{pos: a.pos, name: strings.ToUpper(a.name[:1]) + a.name[1:], kind: a.kind, str: a.str, expr: a.expr})
	}
	return dedupe(renamed, nil), nil
}

func isGoFieldName(name string) bool {
	if name == "" || !isASCIILetter(name[0]) {
		return false
	}
	for i := 1; i < len(name); i++ {
		c := name[i]
		if !isASCIILetter(c) && !(c >= '0' && c <= '9') && c != '_' {
			return false
		}
	}
	return true
}

// injectImport はランタイムの import を package 節と同じ行に足す。行がずれない
func injectImport(p *parser, body string) (string, error) {
	loc := packageClause.FindStringIndex(stripComments(body))
	if loc == nil {
		return "", &Error{File: p.file, Line: 1, Column: 1, Msg: "package clause not found", Phase: "compile"}
	}
	return body[:loc[1]] + fmt.Sprintf("; import %s %q", runtimeName, RuntimeImport) + body[loc[1]:], nil
}

var packageClause = regexp.MustCompile(`(?m)^[ \t]*package[ \t]+[\p{L}_][\p{L}\p{N}_]*`)

// コメントの中の "package" に当たらないよう、コメントを同じ長さの空白にする (改行は残す)
func stripComments(s string) string {
	b := []byte(s)
	for i := 0; i < len(b); {
		switch {
		case b[i] == '/' && i+1 < len(b) && b[i+1] == '/':
			for i < len(b) && b[i] != '\n' {
				b[i] = ' '
				i++
			}
		case b[i] == '/' && i+1 < len(b) && b[i+1] == '*':
			end := strings.Index(string(b[i+2:]), "*/")
			if end < 0 {
				end = len(b) - i - 2
			}
			for j := i; j < i+end+4 && j < len(b); j++ {
				if b[j] != '\n' {
					b[j] = ' '
				}
			}
			i += end + 4
		case b[i] == '"' || b[i] == '`':
			// package 節より前に文字列は来ないので、ここで止めてよい
			return string(b)
		default:
			i++
		}
	}
	return string(b)
}
